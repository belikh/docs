// Diagrams: line art that a project draws itself, in SVG, and places with `::diagram name Alt text`.
//
// The design system's graphics come from @belikh/jupiter-graphics. A diagram is the same kind of drawing for a figure that the
// graphics set does not have: a wiring plan, a timing chart, a state machine. It follows the same rules, and `jupiter-docs check`
// tests them: thin line art, one stroke width, no fills, no gradients, shadows, images or scripts, and colours that are tokens.
//
//   site       the SVG is inlined and coloured by the theme (currentColor and var(--jp-*) follow light and dark)
//   Markdown   two baked files, <mdOut>/diagrams/<name>-light.svg and -dark.svg, drawn with a <picture>
//   PDF        the baked light file, converted by rsvg-convert with the design system's fonts
import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { resolveFile } from "./resolve.mjs";

export const DIAGRAM_MARKER = "Generated by jupiter-docs";
export const DIAGRAM_NAME = /^[a-z0-9-]+(\/[a-z0-9-]+)*$/;
export const MAX_DIAGRAM_BYTES = 100_000;
/** The colour tokens a diagram may use, as var(--jp-NAME). currentColor is the text colour. */
export const DIAGRAM_TOKENS = ["text", "text-muted", "border", "accent", "ok", "warn", "danger", "info"];
export const MONO_STACK = "JetBrains Mono, ui-monospace, SFMono-Regular, Menlo, Consolas, monospace";

const SHAPES = new Set(["path", "line", "polyline", "polygon", "rect", "circle", "ellipse"]);
const ELEMENTS = new Set(["svg", "g", "defs", "marker", "title", "desc", "text", "tspan", ...SHAPES]);
const camel = (s) => s.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
/** The file name part of a diagram: guides/wiring becomes guides-wiring. */
export const diagramSlug = (name) => name.replace(/\//g, "-");

/** Read the tags of an SVG. Returns { tags, error }. Comments and the XML declaration are dropped; a DOCTYPE, entities and CDATA are refused. */
function tokenize(source) {
  const s = source.replace(/<!--[\s\S]*?-->/g, "").replace(/<\?xml[\s\S]*?\?>/g, "");
  if (/<!DOCTYPE|<!ENTITY|<!\[CDATA\[|<\?/i.test(s)) return { tags: [], error: "DOCTYPE, entities, CDATA and processing instructions are not allowed" };
  const tag = /<(\/?)([A-Za-z][\w:.-]*)((?:\s+[^\s=>/]+(?:\s*=\s*(?:"[^"]*"|'[^']*'))?)*)\s*(\/?)>/g;
  const tags = []; let last = 0; let m;
  while ((m = tag.exec(s))) {
    if (s.slice(last, m.index).includes("<")) return { tags: [], error: "the file is not well-formed SVG" };
    const attrs = {};
    for (const a of m[3].matchAll(/([A-Za-z_:][\w:.-]*)\s*=\s*(?:"([^"]*)"|'([^']*)')/g)) attrs[a[1]] = a[2] ?? a[3];
    tags.push({ name: m[2], closing: m[1] === "/", selfClosing: m[4] === "/", attrs });
    last = tag.lastIndex;
  }
  if (s.slice(last).includes("<")) return { tags: [], error: "the file is not well-formed SVG" };
  return { tags, error: null };
}

const OK_COLOUR = new RegExp(`^(none|currentColor|inherit|var\\(--jp-(${DIAGRAM_TOKENS.join("|")})\\))$`);

/**
 * Check a diagram against the design rules. Returns { errors, warnings, unsafe, hasText, viewBox }. `errors` are rule breaks;
 * `unsafe` is set when the file holds something that must never reach a page (script, event handlers, external references).
 */
export function lintDiagram(source) {
  const errors = []; const warnings = []; let unsafe = false;
  const out = (hasText = false, viewBox = null) => ({ errors, warnings, unsafe, hasText, viewBox });
  if (Buffer.byteLength(source) > MAX_DIAGRAM_BYTES) errors.push(`the file is larger than ${MAX_DIAGRAM_BYTES / 1000} KB`);
  const { tags, error } = tokenize(source);
  if (error) { errors.push(error); unsafe = true; return out(); }
  const root = tags[0];
  if (!root || root.name !== "svg" || root.closing) { errors.push("the file must start with an <svg> element"); return out(); }
  let viewBox = null;
  const vb = (root.attrs.viewBox ?? "").trim().split(/[\s,]+/).map(Number);
  if (vb.length === 4 && vb.every(Number.isFinite) && vb[2] > 0 && vb[3] > 0) viewBox = vb;
  else errors.push('<svg> needs a viewBox of four numbers, for example viewBox="0 0 720 360"');
  if (viewBox && viewBox[2] > 900) warnings.push(`the viewBox is ${viewBox[2]} wide: keep it at 720 or less, or the text prints too small`);

  const stack = []; const widths = new Set(); let hasText = false; let shapeCount = 0; const ids = new Set();
  const fillOf = () => { for (let i = stack.length - 1; i >= 0; i--) if (stack[i].fill !== undefined) return stack[i].fill; return undefined; };
  for (const t of tags) {
    if (t.closing) { stack.pop(); continue; }
    const { name, attrs } = t;
    if (!ELEMENTS.has(name)) {
      errors.push(`<${name}> is not allowed (allowed: ${[...ELEMENTS].join(", ")})`);
      if (/^(script|foreignObject|image|use|a|iframe|animate|animateTransform|set|style)/.test(name)) unsafe = true;
    }
    for (const [k, v] of Object.entries(attrs)) {
      if (/^on/i.test(k)) { errors.push(`<${name}> has the event handler ${k}`); unsafe = true; }
      else if (k === "href" || k === "xlink:href") { errors.push(`<${name}> has a ${k}: diagrams cannot reference other files or elements`); unsafe = true; }
      else if (k === "style") errors.push(`<${name}> has a style attribute: use presentation attributes (stroke, fill) with tokens`);
      else if (["filter", "mask", "clip-path"].includes(k)) errors.push(`<${name}> has ${k}: no filters, masks or shadows`);
      else if (/opacity$/.test(k)) errors.push(`<${name}> has ${k}: do not lower contrast with opacity; use var(--jp-text-muted) for a quieter line`);
      else if (["fill", "stroke", "color"].includes(k)) { if (!OK_COLOUR.test(v.trim())) errors.push(`<${name}> ${k}="${v}": colours are tokens. Use currentColor, none or var(--jp-NAME), where NAME is ${DIAGRAM_TOKENS.join(", ")}`); }
      else if (k === "font-family" && !/^\s*['"]?JetBrains Mono/i.test(v)) errors.push(`<${name}> font-family="${v}": diagram text is JetBrains Mono. Remove font-family`);
      else if (k === "font-weight" && !/^(400|700|normal|bold)$/.test(v)) errors.push(`<${name}> font-weight="${v}": use 400, 700, normal or bold`);
      else if (k === "stroke-width") { const n = Number(v); if (Number.isFinite(n)) widths.add(n); else errors.push(`<${name}> stroke-width="${v}" is not a number`); }
      else if (k === "id") { if (!/^[A-Za-z][\w-]*$/.test(v)) errors.push(`id="${v}" must be letters, digits, - and _`); ids.add(v); }
      for (const u of v.matchAll(/url\(\s*([^)]*)\)/g)) if (!/^#[A-Za-z][\w-]*$/.test(u[1].trim()) || !/^marker-(start|mid|end)$/.test(k)) { errors.push(`<${name}> ${k} uses url(${u[1]}): only marker-start, marker-mid and marker-end may point to a marker in the file`); unsafe = true; }
    }
    if (name === "text") hasText = true;
    if (SHAPES.has(name)) {
      shapeCount++;
      const f = attrs.fill ?? fillOf();
      if (f !== "none") errors.push(`<${name}> is filled: line art has no fills. Set fill="none" on it or on the <svg>`);
    }
    if (!t.selfClosing) stack.push({ name, fill: attrs.fill });
  }
  if (widths.size > 1) errors.push(`stroke widths differ (${[...widths].join(", ")}): a diagram uses one width, set once on the <svg>`);
  else if (widths.size === 1) { const w = [...widths][0]; if (w < 1 || w > 3) warnings.push(`stroke-width ${w} is outside 1 to 3, which is what thin line art looks like at this size`); }
  else if (shapeCount) warnings.push('no stroke-width: set one on the <svg>, for example stroke-width="1.5", so every line has the same weight');
  if (!shapeCount && !hasText) errors.push("the diagram draws nothing");
  return out(hasText, viewBox);
}

/** Read a diagram file. */
export const readDiagram = (file) => readFileSync(file, "utf8");

/** Text is filled, not outlined. Strokes and fill="none" are set once on the <svg> for the lines, and text would inherit both. */
const plainText = (s, fill) => s.replace(/<text\b(?![^>]*\sfill=)/g, `<text fill="${fill}"`).replace(/<text\b(?![^>]*\sstroke=)/g, '<text stroke="none"');

const stripProlog = (s) => s.replace(/<!--[\s\S]*?-->/g, "").replace(/<\?xml[\s\S]*?\?>/g, "").trim();
const prefixIds = (s, uid) => s.replace(/(\sid=)(["'])([^"']+)\2/g, (_, a, q, id) => `${a}${q}${uid}-${id}${q}`).replace(/url\(#([^)]+)\)/g, (_, id) => `url(#${uid}-${id})`);

/** The SVG as an inline element for the site. The page's CSS colours it. Returns "" for a diagram that is not safe. */
export function inlineDiagram(source, name) {
  const info = lintDiagram(source);
  if (info.unsafe || !info.viewBox) return "";
  const uid = `dg${createHash("sha1").update(name).digest("hex").slice(0, 6)}`;
  let s = plainText(prefixIds(stripProlog(source), uid), "currentColor");
  s = s.replace(/<svg\b([^>]*)>/, (m, attrs) => {
    const kept = attrs.replace(/\s(width|height|class|style)=("[^"]*"|'[^']*')/g, "");
    return `<svg${kept} width="${info.viewBox[2]}" class="dx-diagram__svg" aria-hidden="true" focusable="false">`;   // natural width; the page CSS keeps it inside the column
  });
  return s;
}

/** The design system's colours, { light: { text, accent, ... }, dark: {...} }, read from the tokens package. */
export function tokenColours(root) {
  const f = resolveFile("@belikh/jupiter-tokens/tokens.json", root);
  const c = JSON.parse(readFileSync(f, "utf8")).color;
  if (!c?.light || !c?.dark) throw new Error(`${f}: no light and dark colours`);
  return c;
}

/**
 * The SVG as a standalone file for one theme, for places that cannot inherit colour (a Markdown <img>, a PDF). The tokens are
 * replaced by the theme's colours, the size is written out and the text gets the monospace stack. `from` names the source file.
 */
export function bakeDiagram(source, theme, colours, from) {
  const pal = colours[theme]; const info = lintDiagram(source);
  if (info.unsafe) throw new Error(`${from}: the diagram is not safe to publish`);
  let s = stripProlog(source);
  s = s.replace(/var\(--jp-([a-z-]+)\)/g, (m, n) => pal[camel(n)] ?? m).replace(/currentColor/g, pal.text);
  const [, , w, h] = info.viewBox ?? [0, 0, 720, 360];
  s = s.replace(/<svg\b([^>]*)>/, (m, attrs) => {
    let a = attrs.replace(/\s(width|height)=("[^"]*"|'[^']*')/g, "");
    if (!/\sxmlns=/.test(a)) a += ' xmlns="http://www.w3.org/2000/svg"';
    if (info.hasText && !/\sfont-family=/.test(a)) a += ` font-family="${MONO_STACK}"`;
    return `<svg width="${w}" height="${h}"${a}>`;
  });
  s = plainText(s, pal.text);
  return `<!-- ${DIAGRAM_MARKER} from ${from}. Do not edit; change the source and run jupiter-docs build. -->\n${s}\n`;
}
